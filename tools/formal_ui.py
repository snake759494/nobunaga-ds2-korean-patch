        # Compound commands such as 출진시키세요 are not covered by the
        # exact phrase table.  Keep punctuation and line boundaries intact.
        (r'([가-힣]+)세요(?=[！。！？…？?]|\{BR\}|$)', r'\1십시오'),
        (r'([가-힣]+)하죠(?=[！。！？…？?]|\{BR\}|$)', r'\1합니다'),
        (r'([가-힣]+)죠(?=[！。！？…？?]|\{BR\}|$)', r'\1습니다'),
