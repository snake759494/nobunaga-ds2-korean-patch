def formalize(src, text):
    """Return *text* in formal UI style when *src* is a normal UI section."""
    if not text or src not in FORMAL_SOURCES:
        return text
    out = text
    # A phrase rewrite can expose a second ending (for example ``보라`` is
    # rewritten before the following ``구나``).  Iterate to a fixed point so
    # the exact candidate recorded by the builder is also verifier-idempotent.
    for _ in range(3):
        before = out
        for old, new in REPLACEMENTS:
            out = out.replace(old, new)
        out = _rewrite_inflected_questions(out)
        if out == before:
            break
    return out
